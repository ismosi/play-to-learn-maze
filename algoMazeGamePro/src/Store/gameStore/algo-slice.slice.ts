export const alGoSlice = createSlice({
  name: "alGo",
  initialState,
  reducers: {
    setAlgoUnlock: (
      state,
      action: PayloadAction<{ index: string; locked: boolean }>
    ) => {
      const { index, locked } = action.payload;
      const algo = state.algorithms.find((item) => item.index === index);
      if (algo) {
        algo.locked = locked;
      } else {
        console.warn(`Algorithm with index "${index}" not found.`);
      }
    },
  },
});

export const { setAlgoUnlock } = alGoSlice.actions;
export default alGoSlice.reducer;
